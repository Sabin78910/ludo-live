const tables: Record<Lang, Record<StringKey, string>> = { en, ne };

export function t(lang: Lang, key: StringKey, vars: Record<string, string | number> = {}): string {
  const s = tables[lang][key] ?? en[key];
  return s.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? `{${k}}`));
}

export function allKeys(): StringKey[] {
  return Object.keys(en) as StringKey[];
}

export function tableFor(lang: Lang): Record<StringKey, string> {
  return tables[lang];
}

/** Devanagari digits for Nepali number display. */
export function localDigits(lang: Lang, n: number | string): string {
  const s = String(n);
  return lang === "ne" ? s.replace(/[0-9]/g, (d) => "०१२३४५६७८९"[Number(d)]) : s;
}
